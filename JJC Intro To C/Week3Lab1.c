#include <stdio.h>

int main(void) // Main Function
{
	int loop_count; //Loop Control Variable
	
	for (loop_count = 0; loop_count < 10; loop_count += 1) //For Loop
	printf("Num is %d\n", loop_count); //Output
	
	return 0;
}

